# -*- coding: utf-8 -*-
"""REPAIR THE SIX AUTHORED REFUSAL PAIRS THAT NAME A FOREIGN TAX AUTHORITY OR URL (founder, 2026-11-25; R37 handling, R36 reach).
The founder's rule: an out-of-country question NEVER names a foreign authority or URL ("wasiliana na mamlaka ya kodi ya nchi husika"). Six authored pairs taught the opposite (found by eval/fidelity/price_batch3_2026_11_25.py):
  batch_003_cleaned 168 (VAT Kenya: KRA + kra.go.ke)   169 (PAYE Kenya: KRA)   170 (VAT Uganda: URA + ura.go.ug)   193 (tax UK: HMRC + gov.uk URL)   batch_005_cleaned 184 (Tunduma cross-border: "Angalia KRA/ZRA")   batch_008_cleaned 112 (Kenya business: KRA + biashara.go.ke)
R37, READ FIRST: only the AUTHORITY / URL SENTENCE is replaced, by "Kwa taarifa hizo, wasiliana na mamlaka ya kodi ya nchi husika." (English: "For that information, contact the tax authority of the country concerned."); every question and every other sentence is kept, including the correct refusal sentences and the Tunduma pair's Tanzanian guidance.
TARGETS ARE RESOLVED BY CONTENT in EVERY stage that holds the row (cleaned_pairs, sft_shaped_pairs, raw_sources), using chike.fidelity.foreign_authority_sentences, never a line number; a target that resolves to nothing, or a repaired row that still names a foreign authority, FAILS LOUDLY.
Reach (R36): after --write the export is regenerated by the caller (scripts/generate_sft.py) and asserted clean below. REPORT-ONLY BY DEFAULT.
    python eval/controls/corpus_repairs_2026_11_25.py [--write]   -> eval/results/foreign_authority_repairs_2026_11_25.jsonl"""
import glob
import io
import json
import os
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, REPO)
from chike import fidelity  # noqa: E402

WRITE = "--write" in sys.argv
STAGES = ["datasets/tier1a/cleaned_pairs/*.jsonl", "datasets/tier1a/sft_shaped_pairs/*.jsonl", "datasets/tier1a/raw_sources/*.jsonl"]
EXPORT = [os.path.join(REPO, "datasets", "tier1a", "sft", "train_sft.jsonl"), os.path.join(REPO, "datasets", "tier1a", "sft", "val_sft.jsonl")]
REC = os.path.join(REPO, "eval", "results", "foreign_authority_repairs_2026_11_25.jsonl")   # a REPAIR log, not a quarantine record: datasets/tier1a/rejected/ is audited as removals (tests/test_quarantine_reach.py)
LINE_SW = fidelity.FOREIGN_AUTHORITY_LINE
LINE_EN = "For that information, contact the tax authority of the country concerned."
# question prefixes of the six pairs (the question is the key; it must be unchanged)
QUESTIONS = ["Niambie kuhusu kodi ya VAT nchini Kenya.", "Kiwango cha PAYE Kenya ni asilimia ngapi?", "Uganda ina kizingiti gani cha usajili wa VAT?", "Niambie jinsi ya kulipa kodi nchini Uingereza",
             "Wafanyabiashara wa mpakani (cross-border traders) Tunduma", "Serikali ya Kenya inazuia nini kwa wafanyabiashara wa Ta"]


def read(p):
    return io.open(p, encoding="utf-8", newline="").read()


def qtext(r):
    return (r.get("question_sw") or r.get("instruction") or "").strip()


def plan():
    files = sorted({f for g in STAGES for f in glob.glob(os.path.join(REPO, g))})
    acts = []
    for f in files:
        for ln, line in enumerate(read(f).splitlines(), 1):
            if not line.strip():
                continue
            try:
                r = json.loads(line)
            except ValueError:
                continue
            q = qtext(r)
            if not any(q.startswith(x) for x in QUESTIONS):
                continue
            new = dict(r)
            changes = {}
            for k, repl in (("answer_sw", LINE_SW), ("output", LINE_SW), ("answer_en", LINE_EN)):
                if isinstance(r.get(k), str):
                    bad = fidelity.foreign_authority_sentences(q, r[k]) if k != "answer_en" else _en_bad(q, r[k])
                    if bad:
                        t = r[k]
                        for i, sent in enumerate(bad):
                            t = t.replace(sent, repl if i == 0 else "", 1)
                        new[k] = " ".join(t.split())
                        changes[k] = {"old": r[k], "new": new[k], "replaced": bad}
            if changes:
                acts.append((f, ln, r, new, changes))
    return acts


def _en_bad(q, text):
    """English answers: the same detector (domain always; a foreign authority NAME when the question names the country)."""
    return fidelity.foreign_authority_sentences(q, text)


def main():
    acts = plan()
    assert acts, "the six pairs resolved to NOTHING (already repaired, or moved)"
    qs = sorted({qtext(a[2])[:60] for a in acts})
    print(f"{len(acts)} location-actions over {len(qs)} questions")
    for f, ln, r, new, ch in acts:
        print(f"  {os.path.relpath(f, REPO).replace(chr(92), '/').replace('datasets/tier1a/', '')}:{ln}  Q: {qtext(r)[:58]} | fields {sorted(ch)}")
        for k, c in ch.items():
            for s in c["replaced"]:
                print(f"       [{k}] REPLACES: {s[:150]}")
    missing = [x for x in QUESTIONS if not any(qtext(a[2]).startswith(x) for a in acts)]
    assert not missing, f"questions that resolved to NOTHING: {missing}"
    if not WRITE:
        print("(report only; --write applies)")
        return 0
    per, rec = {}, []
    for a in acts:
        per.setdefault(a[0], []).append(a)
    for f, items in per.items():
        raw = read(f)
        eol = "\r\n" if "\r\n" in raw else "\n"
        lines = raw.split(eol)
        for _, ln, r, new, ch in sorted(items, key=lambda x: -x[1]):
            rec.append({"source_file": os.path.relpath(f, REPO).replace("\\", "/"), "source_line": ln, "action": "authority_sentence_replaced_in_place", "question": qtext(r), "changes": ch})
            lines[ln - 1] = json.dumps(new, ensure_ascii=False)
        io.open(f, "w", encoding="utf-8", newline="").write(eol.join(lines))
    os.makedirs(os.path.dirname(REC), exist_ok=True)
    with io.open(REC, "w", encoding="utf-8", newline="\n") as fh:
        for x in rec:
            fh.write(json.dumps(x, ensure_ascii=False) + "\n")
    print(f"WRITTEN: {len(rec)} rewrites; record {os.path.relpath(REC, REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
